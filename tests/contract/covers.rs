use crate::harness::{NOT_MET, Project, calc, calc_crate, readme, test_fn};

const LIB: &str = "\
pub fn add(a: i32, b: i32) -> i32 {
    a + b
}

pub struct Twice;

impl Twice {
    pub fn twice(&self, x: i32) -> i32 {
        x * 2
    }

    pub fn thrice(&self, x: i32) -> i32 {
        x * 3
    }
}

mod inner {
    pub fn deep() {}
}

#[cfg(feature = \"extra\")]
pub fn gated() {}

pub trait Shape {
    fn area(&self) -> u32 {
        0
    }
    fn sides(&self) -> u32;
}

#[cfg(test)]
fn probe() {}

#[cfg(test)]
impl Twice {
    fn probe() {}
}

#[cfg(test)]
trait Hidden {
    fn hidden(&self) {}
}

#[cfg(test)]
mod tests {
    fn hidden() {}
}
";

/// calc, covering `lines`, over src/lib.rs, src/sub/more.rs, a generated
/// src/gen.rs and code outside `src/`.
fn project(lines: &str) -> Project {
    let p = calc(&["A1"], &test_fn("adds", &["calc/A1"]));
    p.write(
        "contract/calc/README.md",
        &format!("{}```covers\n{lines}```\n", readme(&["A1"])),
    )
    .write("src/lib.rs", LIB)
    .write("src/sub/more.rs", "pub fn more() {}\n")
    .write("src/gen.rs", "// @generated by a tool\npub fn made() {}\n")
    .write("build.rs", "fn main() {}\n")
    .write(".hidden/src/x.rs", "pub fn x() {}\n")
    .write("target/src/y.rs", "pub fn y() {}\n");
    p
}

#[impish::contract("covers/A1")]
fn covers_lines_name_real_code() {
    let good = "src/lib.rs::add\nsrc/lib.rs::Twice\nsrc/lib.rs::Twice::twice\n\
                src/lib.rs::deep\nsrc/sub/...\nsrc/lib.rs\n";
    let out = project(good).check();
    assert_eq!(out.code, Some(0), "{}", out.stderr);

    let out = project(
        "src/lib.rs::\na::b::c::d\n/...\nsrc/lib.rs::sub\nsrc/lib.rs::Twice::half\n\
         src/lib.rs::Once::twice\nsrc/gone.rs\nsrc/gone/...\nsrc/gen.rs\nsrc/lib.rs::hidden\n",
    )
    .check();
    assert_eq!(out.code, Some(1));
    let file = "contract/calc/README.md";
    let malformed = "is not <file>, <dir>/..., <file>::<item> or <file>::<Type>::<method>";
    assert_eq!(
        out.stderr,
        format!(
            "{file}: covers line `src/lib.rs::` {malformed}\n\
             {file}: covers line `a::b::c::d` {malformed}\n\
             {file}: covers line `/...` {malformed}\n\
             {file}: covers `src/lib.rs::sub`, which doesn't exist\n\
             {file}: covers `src/lib.rs::Twice::half`, which doesn't exist\n\
             {file}: covers `src/lib.rs::Once::twice`, which doesn't exist\n\
             {file}: covers `src/gone.rs`, which doesn't exist\n\
             {file}: covers `src/gone/...`, which doesn't exist\n\
             {file}: covers `src/gen.rs`, which doesn't exist\n\
             {file}: covers `src/lib.rs::hidden`, which doesn't exist\n\
             {NOT_MET}\n"
        )
    );
}

/// The stubs `regen` packs for `primitive`: the functions it owns.
fn stubs(p: &Project, primitive: &str, file: &str) -> String {
    let out = p.run(&["regen", primitive]);
    assert_eq!(out.code, Some(0), "{}", out.stderr);
    p.read(&format!("target/impish/regen/{primitive}/stubs/{file}"))
}

#[impish::contract("covers/A2")]
fn the_most_specific_claim_owns_a_function() {
    let p = project("src/...\nsrc/lib.rs\n");
    for (name, lines) in [
        ("tally", "src/lib.rs::Twice\nsrc/sub/more.rs\n"),
        ("zeta", "src/lib.rs::Twice::twice\nsrc/lib.rs\n"),
    ] {
        p.write(
            &format!("contract/{name}/README.md"),
            &format!("{}```covers\n{lines}```\n", readme(&["A1"])),
        )
        .write(
            &format!("tests/contract/{name}.rs"),
            &test_fn("holds", &[&format!("{name}/A1")]),
        );
    }
    assert_eq!(
        stubs(&p, "calc", "src/lib.rs"),
        "pub fn add(a: i32, b: i32) -> i32 {\n    todo!()\n}\n\n\
         pub fn deep() {\n    todo!()\n}\n\n\
         #[cfg(feature = \"extra\")]\npub fn gated() {\n    todo!()\n}\n"
    );
    assert_eq!(
        stubs(&p, "tally", "src/lib.rs"),
        "impl Twice {\n    pub fn thrice(&self, x: i32) -> i32 {\n        todo!()\n    }\n}\n"
    );
    assert_eq!(
        p.read("target/impish/regen/tally/stubs/src/sub/more.rs"),
        "pub fn more() {\n    todo!()\n}\n"
    );
    assert_eq!(
        stubs(&p, "zeta", "src/lib.rs"),
        "impl Twice {\n    pub fn twice(&self, x: i32) -> i32 {\n        todo!()\n    }\n}\n"
    );
}

#[impish::contract("covers/A3")]
fn code_outside_the_contract_is_listed() {
    let p = project("src/lib.rs::add\n");
    let out = p.run(&["check", "--outside"]);
    assert_eq!(out.code, Some(0), "{}", out.stderr);
    assert!(
        out.stdout.ends_with(
            "Outside the Contract:\n  src/lib.rs::Twice::twice\n  src/lib.rs::Twice::thrice\n  \
             src/lib.rs::gated\n  src/lib.rs::Shape::area\n  src/lib.rs::deep\n  src/sub/more.rs::more\n"
        ),
        "{}",
        out.stdout
    );
    assert!(!p.check().stdout.contains("Outside"));
}

#[impish::contract("covers/A4")]
fn the_covered_share_is_reported() {
    let p = project("src/lib.rs::add\nsrc/lib.rs::deep\n");
    let out = p.run(&["check", "--write"]);
    assert_eq!(out.code, Some(0), "{}", out.stderr);
    assert!(
        out.stdout
            .contains("\ncode: 2 of 7 functions in the Contract (28.6%)\n"),
        "{}",
        out.stdout
    );
    let coverage: serde_json::Value =
        serde_json::from_str(&p.read("contract/coverage.json")).unwrap();
    assert_eq!(
        coverage["code"],
        serde_json::json!({"covered": 2, "total": 7, "percent": 28.6})
    );

    let bare = calc(&["A1"], &test_fn("adds", &["calc/A1"]));
    let out = bare.run(&["check", "--write"]);
    assert!(!out.stdout.contains("code:"), "{}", out.stdout);
    let coverage: serde_json::Value =
        serde_json::from_str(&bare.read("contract/coverage.json")).unwrap();
    assert!(coverage.get("code").is_none(), "{coverage}");
}

#[impish::contract("covers/A5")]
fn mutate_breaks_what_a_primitive_owns() {
    let p = calc_crate(
        "#[impish::contract(\"calc/A1\")]\n\
         fn adds() {\n    assert_eq!(calc::add(2, 3), 5);\n}\n",
    );
    p.write(
        "src/lib.rs",
        "pub fn add(a: i32, b: i32) -> i32 {\n    fn plus(a: i32, b: i32) -> i32 {\n        \
         a + b\n    }\n    plus(a, b)\n}\n\n\
         pub fn negate(a: i32) -> i32 {\n    -a\n}\n",
    )
    .write(
        "contract/calc/README.md",
        &format!("{}```covers\nsrc/lib.rs\n```\n", readme(&["A1"])),
    )
    .write(
        "contract/neg/README.md",
        &format!("{}```covers\nsrc/lib.rs::negate\n```\n", readme(&["A1"])),
    );
    let out = p.mutate("calc");
    assert!(
        out.stdout
            .contains("replace + with - in add::plus  killed by calc/A1\n"),
        "{}{}",
        out.stdout,
        out.stderr
    );
    assert!(!out.stdout.contains("negate"), "{}", out.stdout);
}
